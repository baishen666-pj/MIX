// Round table: 32x32 top-down
export const ROUND_TABLE_SPRITE: FurnitureSprite = {
  width: 32, height: 32,
  data: Array.from({ length: 32 }, (_, y) =>
    Array.from({ length: 32 }, (__, x) => {
      const dx = x - 16, dy = y - 16
      const dist = Math.sqrt(dx * dx + dy * dy)
      if (dist > 15) return 0
      if (dist > 13) return 3
      if (dist > 11) return 2
      return 1
    })
  ),
}

